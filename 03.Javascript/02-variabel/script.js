// 
// ==================================================
// Variabel
// ==================================================
// Variabel adalah tempat untuk menyimpan data
// 


// 
// ==================================================
// 1. Let
// ==================================================
// Let digunakan untuk membuat variabel yang nilainya boleh di ubah
// 

let nama = "Azis";

console.log(nama);

// Nilai variabel let masih bisa di ubah.
nama = "budi";
console.log(nama);


// 
// =================================================
// 2. Const
// =================================================
// Const digunakan untuk membuat variabel yang nilainya tidak boleh diganti setelah di berikan nilai
// 

const negara="Indonesia";

console.log(negara);

// 
// =================================================
// 3. VAR
// =================================================
//
// Var adalah cara lama untuk membuat variabel
// saat belajar Javascript moderen,
//  Kita biasanya sering menggunakan 
// A. Let
// B. Const

var kota = "Gorontalo";

console.log(kota);

// VAR masih bisa di ubah
kota = "Manado";
console.log(kota);


// 
// ===================================================
// 4. Variabel Dengan Angka 
// ===================================================
// 
let umur = 30;
console.log(umur);

let harga = 15000;
console.log(harga);


// 
// ====================================================
// 5. Menggunakan Beberapa Variabel
// ====================================================
// 

let namaLengkap ="Azis Ance";
let pekerjaan = "Programmer";
let tahun = 2026;

console.log(namaLengkap);
console.log(pekerjaan);
console.log(tahun);